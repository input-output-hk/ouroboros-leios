#!/usr/bin/env python3
"""The stage table (report section 4, table b) and the closure-tail sub-table
(4.3) of the testnet windows, printed as Markdown from the saved outputs of the
six instrument passes, so every number in those tables is regenerated by one
command rather than derived by hand.

    stage_table.py [--outputs DIR] [--archive-only] [--classes | --voters] WINDOW [WINDOW ...]

WINDOW     a key of WINDOWS below (testnet windows and cluster runs)
--outputs  the saved outputs folder (default: outputs/ in this repository)
--archive-only   read a testnet window's <WINDOW>/archive-only/ outputs (the
           SPO archive alone) instead of <WINDOW>/ (archive and IOG monitoring
           merged); the merged outputs are the report's, the archive-only ones
           the check at lower reporting weight
--classes  print, instead of the tables, the readings by EB size class behind
           4.3.1's prose: the 6,000-and-up class of the closure-tail sub-table
           split at the reference cap (8,550 references and up), with the
           nodes that received the body and the closure per EB, and the
           validation by EB size class (validation_classes.md)
--voters   print, instead of the tables, the two voter-stage tables of 8.1
           (voter_stages.csv): per set and EB size bin, where the voters
           lost the EB (closure by 3 s / after / never, validation within
           4 s / longer / never) and the vote's outcome (voted / late, the
           late votes by cause, the EBs with late voters over a quarter,
           the certified share of the EBs the chain could certify), with
           the sets as row groups in the order given

Inputs under <outputs>/<WINDOW>/, written by the instruments:
  diffusion.csv, diffusion-body.csv     instruments/diffusion_nodes.py, closure and body stage
  validation_nodes.csv                  instruments/validation_pairs.sql (cluster_validation_pairs.sql)
  tally_quorum_nodes.csv, tally_quorum_ebs.csv   instruments/tally_quorum.sql (cluster_tally_quorum.sql)
  closure_fleet_per_eb.csv              instruments/closure_fleet.sql (testnet only)
  voters.csv                            instruments/coverage.sql (testnet only, the reporting weight)
  validation_classes.md                 instruments/validation_classes.py (testnet only; --classes)
  voter_stages.csv                      instruments/voter_stages.py (--voters)
A missing input prints n/a for its rows.

Rows follow the layout agreed on 2026-10-30: no p50; diffusion at the median
reporting node with the share of nodes whose p90 clears the deadline; the
validation row is the p90 of (validated - max(closure, slot + 3 s)) per node
(100+ records), median and quartiles across nodes; the tally row the p90 per
node (50+ EBs with a quorum) of the age at which the node's own tally reached
0.75; the vote rate the median node's share of eligible EBs voted; the last
row the certified share of the eligible EBs whose quorum some reporting node
saw.
"""
import argparse, csv, os, statistics as st, sys

WINDOWS = {
    "f1-high": dict(label="testnet 40 kB / 260 kB, loaded hours"),
    "f2-high": dict(label="testnet 308 kB / 2 MB, loaded hours"),
    "1kb": dict(label="testnet 308 kB / 2 MB, 1 kB transactions"),
    # cluster runs: all nodes observed, no archive-only variant, no closure-fleet or voters table
    "cluster-40k260k": dict(label="cluster 40 kB / 260 kB, 200 B", cluster=True),
    "cluster-100k1m": dict(label="cluster 100 kB / 1 MB, 200 B", cluster=True),
    "cluster-100k1m-374": dict(label="cluster 100 kB / 1 MB, 374 B", cluster=True),
    "cluster-100k1m-374-patched": dict(label="cluster 100 kB / 1 MB, 374 B, changed build", cluster=True),
}
OUTPUTS = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "outputs"))
ROWS = ["body: p90 / p95; nodes with p90 under 3 s",
        "closure: p90 / p95; nodes with p90 under 3 s / 7 s; not completed",
        "applied share at the closure",
        "validation, start to validated, p90",
        "vote tally reaches the quorum, p90",
        "vote rate on eligible EBs",
        "quorums that became certificates"]
BINS = [(0, 2000, "under 2,000 txs"), (2000, 4000, "2,000-4,000"), (4000, 6000, "4,000-6,000"), (6000, 1e12, "6,000 and up")]


def read(path):
    if not os.path.exists(path):
        return None
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def q(xs, p):
    xs = sorted(xs)
    if not xs:
        return float("nan")
    i = (len(xs) - 1) * p
    lo = int(i)
    hi = min(lo + 1, len(xs) - 1)
    return xs[lo] + (xs[hi] - xs[lo]) * (i - lo)


def pct(n, d):
    """A whole percentage, except that a value which would round to 100 % without being exact
    keeps one decimal, so that 820 of 823 reads 99.6 % and not 100 %."""
    if not d:
        return "n/a"
    v = 100.0 * n / d
    return "%.1f %%" % v if n != d and round(v) == 100 else "%.0f %%" % v


def diffusion_row(rows, befores):
    if rows is None:
        return "n/a"
    p90 = [float(r["p90"]) for r in rows]
    p95 = [float(r["p95"]) for r in rows]
    shares = " / ".join(pct(sum(p < b for p in p90), len(p90)) for b in befores)
    return "%.2f / %.2f s; %s" % (st.median(p90), st.median(p95), shares)


def column(outputs, name, archive_only):
    w = WINDOWS[name]
    d = os.path.join(outputs, name, "archive-only") if archive_only and not w.get("cluster") else os.path.join(outputs, name)
    val = read(os.path.join(d, "validation_nodes.csv"))
    tn = read(os.path.join(d, "tally_quorum_nodes.csv"))
    te = read(os.path.join(d, "tally_quorum_ebs.csv"))
    fleet = read(os.path.join(d, "closure_fleet_per_eb.csv")) if not w.get("cluster") else None
    voters = read(os.path.join(d, "voters.csv")) if not w.get("cluster") else None
    clo = read(os.path.join(d, "diffusion.csv"))
    body = read(os.path.join(d, "diffusion-body.csv"))
    out = {}
    out[ROWS[0]] = diffusion_row(body, [3])
    if clo is not None:
        never = st.median(float(r["never"]) for r in clo)
        out[ROWS[1]] = diffusion_row(clo, [3, 7]) + "; %.0f %%" % never
        votes = [float(r["vote_pct"]) for r in clo if r["vote_pct"] not in ("", None)]
        out[ROWS[5]] = pct(st.median(votes), 100.0) if votes else "n/a"
    else:
        out[ROWS[1]] = out[ROWS[5]] = "n/a"
    if val is not None:
        # per node (100+ records): the p90 of the duration and the applied share, from the instrument's per-node summary
        nodes = [r for r in val if int(r["records"]) >= 100]
        p90 = [float(r["p90"]) for r in nodes]
        applied = [100.0 * float(r["applied"]) / max(1.0, float(r["applied"]) + float(r["reapplied"])) for r in nodes]
        out[ROWS[2]] = "%.0f %%" % st.median(applied)
        out[ROWS[3]] = "%.2f s, nodes' quartiles %.2f to %.2f" % (st.median(p90), q(p90, 0.25), q(p90, 0.75))
    else:
        out[ROWS[2]] = out[ROWS[3]] = "n/a"
    if tn is not None:
        p90 = [float(r["p90"]) for r in tn if int(r["ebs_with_quorum"]) >= 50]
        out[ROWS[4]] = "%.2f s, nodes' quartiles %.2f to %.2f" % (st.median(p90), q(p90, 0.25), q(p90, 0.75)) if p90 else "n/a"
    else:
        out[ROWS[4]] = "n/a"
    if te is not None:
        qs = [r for r in te if r["quorum_somewhere"] == "true"]
        cert = sum(r["certified"] == "1" for r in qs)
        out[ROWS[6]] = "%s, %s of %s quorums seen" % (pct(cert, len(qs)), format(cert, ","), format(len(qs), ","))
    else:
        out[ROWS[6]] = "n/a"
    # caption: reporting nodes and pools (closure table), committee pools and reporting weight per window (voters)
    cap = []
    if clo is not None and w.get("cluster"):
        cap.append("all %d nodes observed, equal weight" % len(clo))
    elif clo is not None:
        cap.append("%d reporting nodes from %d pools" % (len(clo), len({r["pool"] for r in clo})))
    if voters is not None:
        # a window that straddles an epoch holds two committees (weights sum to 2): the reporting share is of the window's total
        wins = {}
        for r in voters:
            d = wins.setdefault(r["win"], {"pools": set(), "w": 0.0, "tot": 0.0})
            d["pools"].add(r["pool_id"])
            d["tot"] += float(r["weight"])
            if r["reporting"] == "true":
                d["w"] += float(r["weight"])
        sizes = sorted(len(d["pools"]) for d in wins.values())
        ws = sorted(d["w"] / d["tot"] for d in wins.values() if d["tot"])
        rng = lambda xs, f: f % xs[0] if f % xs[0] == f % xs[-1] else (f % xs[0]) + "-" + (f % xs[-1])
        cap.append("committee of %s pools per window, reporting weight %s" % (rng(sizes, "%d"), rng(ws, "%.2f")))
    sub = None
    if fleet is not None:
        sub = []
        for lo, hi, lab in BINS:
            rs = [r for r in fleet if lo <= float(r["txs"]) < hi]
            if not rs:
                continue
            cert = [r for r in rs if r["certified"] in ("1", "true")]
            t90 = [float(r["t90"]) for r in rs]
            t95 = [float(r["t95"]) for r in rs]
            kb = ("%s kB" % format(round(q([float(r["closure"]) for r in cert], 0.5) / 1e3), ",")) if cert and "closure" in rs[0] else "n/a"
            t90p50 = q(t90, 0.5)
            sub.append((lab, len(rs), pct(len(cert), len(rs)), kb, "%.2f s" % t90p50 if t90p50 < 1e8 else "never",
                        pct(sum(t < 7 for t in t90), len(rs)), pct(sum(t < 7 for t in t95), len(rs))))
    return w["label"], out, "; ".join(cap), sub


def classes(outputs, name):
    """The readings by EB size class behind 4.3.1's prose: the 6,000-and-up class split at the reference
    cap, from the per-EB closure-fleet rows (nodes that received the body and the closure), and the
    validation by class, passed through from validation_classes.md."""
    d = os.path.join(outputs, name)
    fleet = read(os.path.join(d, "closure_fleet_per_eb.csv"))
    print("The 6,000-and-up class split at S_EB, %s:\n" % name)
    print("| EB size | EBs | certified | closure never at 90 % of nodes | nodes that received the EB (p50) | received its body (p50) | completed its closure (p50) |")
    print("|---|---|---|---|---|---|---|")
    if fleet is None or "nodes_body" not in fleet[0]:
        print("| n/a | | | | | | |")
    else:
        for lo, hi, lab in [(6000, 8550, "6,000 to 8,549 references"), (8550, 1e12, "at S_EB, 8,550 references and up")]:
            rs = [r for r in fleet if lo <= float(r["txs"]) < hi]
            if not rs:
                continue
            print("| %s | %d | %d | %d | %.0f | %.0f | %.0f |" % (
                lab, len(rs), sum(r["certified"] in ("1", "true") for r in rs), sum(float(r["t90"]) >= 1e8 for r in rs),
                q([float(r["nodes"]) for r in rs], 0.5), q([float(r["nodes_body"]) for r in rs], 0.5), q([float(r["nodes_closure"]) for r in rs], 0.5)))
    print("\nValidation by EB size class, %s:\n" % name)
    path = os.path.join(d, "validation_classes.md")
    print(open(path).read().rstrip() if os.path.exists(path) else "n/a")
    print()


def voters(outputs, names):
    """The two voter-stage tables of 8.1 from each set's voter_stages.csv, the sets as row groups."""
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "instruments"))
    import voter_stages as vs
    sets = [(WINDOWS[n]["label"], read(os.path.join(outputs, n, "voter_stages.csv")) or []) for n in names]
    print(vs.STAGES_HEAD.replace("| EB size", "| set | EB size", 1))
    print("|---|---|---:|---:|---:|---:|")
    for label, rows in sets:
        for r in rows:
            print(vs.stages_row(r, label))
    print()
    print(vs.OUTCOME_HEAD.replace("| EB size", "| set | EB size", 1))
    print("|---|---|---:|---:|---:|---:|---:|")
    for label, rows in sets:
        for r in rows:
            print(vs.outcome_row(r, label))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("windows", nargs="+", choices=sorted(WINDOWS))
    ap.add_argument("--outputs", default=OUTPUTS)
    ap.add_argument("--archive-only", action="store_true")
    ap.add_argument("--classes", action="store_true")
    ap.add_argument("--voters", action="store_true")
    a = ap.parse_args()
    if a.classes:
        for w in a.windows:
            classes(a.outputs, w)
        return
    if a.voters:
        voters(a.outputs, a.windows)
        return
    cols = [column(a.outputs, w, a.archive_only) for w in a.windows]
    print("| stage | " + " | ".join(c[0] for c in cols) + " |")
    print("|---|" + "---|" * len(cols))
    for r in ROWS:
        print("| %s | %s |" % (r, " | ".join(c[1][r] for c in cols)))
    for name, c in zip(a.windows, cols):
        print("\nCaption, %s%s: %s." % (name, " (archive only)" if a.archive_only else "", c[2] or "n/a"))
        if c[3]:
            print("\nClosure at 90 %% of nodes by EB size, %s:\n" % name)
            print("| EB size | EBs | certified | certified closure p50 | 90 % of nodes hold it by (p50 over EBs) | EBs held by 90 % within 7 s | by 95 % within 7 s |")
            print("|---|---|---|---|---|---|---|")
            for row in c[3]:
                print("| " + " | ".join(str(x) for x in row) + " |")


if __name__ == "__main__":
    main()
